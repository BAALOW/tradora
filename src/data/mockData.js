export function computeJournalStats(tradeList) {
  const total = tradeList.length
  const wins = tradeList.filter((t) => t.result === 'WIN')
  const losses = tradeList.filter((t) => t.result === 'LOSS')
  const be = tradeList.filter((t) => t.result === 'BE')
  const winRate = total ? (wins.length / total) * 100 : 0
  const netPnl = tradeList.reduce((sum, t) => sum + t.pnl, 0)
  const grossWin = wins.reduce((sum, t) => sum + t.pnl, 0)
  const grossLoss = Math.abs(losses.reduce((sum, t) => sum + t.pnl, 0))
  const profitFactor = grossLoss ? grossWin / grossLoss : grossWin > 0 ? Infinity : 0
  const avgWin = wins.length ? grossWin / wins.length : 0
  const avgLoss = losses.length ? grossLoss / losses.length : 0
  const avgRisk = total ? tradeList.reduce((sum, t) => sum + (t.riskPct || 0), 0) / total : 0
  const expectancy = total ? netPnl / total : 0
  const avgRRNum =
    total &&
    tradeList.reduce((sum, t) => {
      const parts = String(t.rr).split(':')
      const rrVal = parts.length === 2 ? Number(parts[1]) / Number(parts[0]) : 0
      return sum + rrVal
    }, 0) / total

  return {
    total,
    wins: wins.length,
    losses: losses.length,
    be: be.length,
    winRate,
    netPnl,
    profitFactor,
    avgWin,
    avgLoss,
    avgRisk,
    expectancy,
    avgRR: avgRRNum || 0,
  }
}